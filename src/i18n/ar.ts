function translateElement(root: Node) {
  const visit = (node: Node) => {
    if (node.nodeType === Node.TEXT_NODE) {
      const original = node.nodeValue ?? '';
      const translated = translateText(original);
      if (translated !== original) node.nodeValue = translated;
      return;
    }
    if (!(node instanceof Element)) return;
    for (const attr of attributes) {
      const value = node.getAttribute(attr);
      if (value) {
        const translated = translateText(value);
        if (translated !== value) node.setAttribute(attr, translated);
      }
    }
    for (const child of [...node.childNodes]) visit(child);
  };
  visit(root);
}

export function installArabicUi() {
  document.documentElement.lang = 'ar';
  document.documentElement.dir = 'rtl';
  translateElement(document.body);

  const nativeAlert = window.alert.bind(window);
  const nativeConfirm = window.confirm.bind(window);
  const nativePrompt = window.prompt.bind(window);
  window.alert = (message?: unknown) => nativeAlert(translateText(String(message ?? '')));
  window.confirm = (message?: unknown) => nativeConfirm(translateText(String(message ?? '')));
  window.prompt = (message?: string, defaultValue?: string) => nativePrompt(translateText(String(message ?? '')), defaultValue === undefined ? undefined : translateText(defaultValue));

  const observer = new MutationObserver((records) => {
    for (const record of records) {
      if (record.type === 'characterData') translateElement(record.target);
      for (const node of record.addedNodes) translateElement(node);
      if (record.type === 'attributes' && record.target instanceof Element) {
        const target = record.target;
        for (const attr of attributes) {
          const value = target.getAttribute(attr);
          if (value) {
            const translated = translateText(value);
            if (translated !== value) target.setAttribute(attr, translated);
          }
        }
      }
    }
  });
  observer.observe(document.body, { subtree: true, childList: true, characterData: true, attributes: true, attributeFilter: attributes });
  return () => observer.disconnect();
}
